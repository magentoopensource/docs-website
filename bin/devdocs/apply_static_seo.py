#!/usr/bin/env python3
"""
Apply the search head (title, description, canonical, Open Graph, Twitter card, JSON-LD) and the link and
heading clean-up to the pages that are edited in place:

  - the hand-written /developer pages (everything except the 70 generated by build_html_pages.py)
  - every /the-core page (a static copy; the upstream the-core repo does not carry the edits made here)

Idempotent: the head block sits between <!-- seo:start --> and <!-- seo:end --> and is replaced on re-run.
A page's dateModified is kept from the existing block; pass --refresh to take the current git date instead
(do that after editing a page's content).

  python3 bin/devdocs/apply_static_seo.py            # apply
  python3 bin/devdocs/apply_static_seo.py --check    # exit 1 if any page would change (CI / pre-commit use)
"""

import os
import posixpath
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import seo_head as sh  # noqa: E402
import static_seo_data as data  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
PUBLIC = os.path.join(ROOT, 'public')


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def existing_date(page):
    m = re.search(r'"dateModified":\s*"([^"]+)"', page)
    return m.group(1) if m else None


def set_title_and_description(page, title, description):
    page = re.sub(r'<title>.*?</title>', lambda m: '<title>%s</title>' % sh.esc(title), page, count=1, flags=re.S)
    meta = '<meta name="description" content="%s">' % sh.esc(description)
    if re.search(r'<meta name="description"[^>]*>', page):
        page = re.sub(r'<meta name="description"[^>]*>', lambda m: meta, page, count=1)
    else:
        page = re.sub(r'(</title>)', lambda m: m.group(1) + '\n    ' + meta, page, count=1)
    return page


def insert_block(page, block):
    return re.sub(r'(<meta name="description"[^>]*>)', lambda m: m.group(1) + '\n    ' + block, page, count=1)


def page_date(page, rel_path, refresh):
    if not refresh:
        d = existing_date(page)
        if d:
            return d
    return sh.git_date(rel_path, ROOT)


# ------------------------------------------------------------------ developer pages

def fix_dev_links(page):
    return re.sub(r'href="index\.html(?=[#"])', 'href="./', page)


def apply_dev(name, refresh):
    path = os.path.join(PUBLIC, 'developer', name)
    page = sh.strip_block(read(path))
    legacy = name in data.DEV_LEGACY
    if legacy:
        title, desc, target = data.DEV_LEGACY[name]
        parents = [data.DEV_HOME]
        canonical_override = sh.abs_url('/developer/' + target)
    else:
        title, desc, parents = data.DEV_PAGES[name]
        canonical_override = data.DEV_CANONICAL_OVERRIDE.get(name)
    full_title = title if name == 'index.html' else sh.with_suffix(title)
    sh.check_description(desc, name)
    url_path = '/developer/' if name == 'index.html' else '/developer/' + name
    crumbs = [(n, sh.abs_url(p)) for n, p in parents] + [(title if name != 'index.html' else 'Developer Documentation', sh.abs_url(url_path))]
    if name == 'index.html':
        crumbs = [('Home', sh.abs_url('/developer/'))]
    page = set_title_and_description(page, full_title, desc)
    date = page_date(read(path), 'public/developer/' + name, refresh)
    page = insert_block(page, sh.seo_block(full_title, desc, url_path, title, crumbs, date, canonical_override))
    page = fix_dev_links(page)
    if name == 'index.html':
        page = index_h1(page)
    return path, page


def index_h1(page):
    """The hero slogan stays exactly as it looks, but is no longer the H1: the H1 names the subject (SEO-21)."""
    old = re.search(r'<h1 class="([^"]*)">\s*Build with the Community\.\s*</h1>', page)
    if not old:
        return page
    new = ('<h1 class="sr-only">Magento Open Source developer documentation</h1>\n'
           '                <p class="%s">\n                    Build with the Community.\n                </p>' % old.group(1))
    return page.replace(old.group(0), new, 1)


# ------------------------------------------------------------------ the-core pages

def core_pages():
    out = []
    for dirpath, _, files in os.walk(os.path.join(PUBLIC, 'the-core')):
        for f in files:
            if f.endswith('.html'):
                out.append(os.path.join(dirpath, f))
    return sorted(out)


def core_key(path):
    """(url path, module or None, topic key)"""
    rel = os.path.relpath(path, PUBLIC).replace(os.sep, '/')
    m = re.match(r'the-core/modules/(Magento_\w+)/html/([\w-]+)\.html$', rel)
    if m:
        topic = m.group(2)
        url = '/the-core/modules/%s/html/%s' % (m.group(1), '' if topic == 'index' else topic + '.html')
        return url, m.group(1), topic
    return '/the-core/', None, 'root'


def dev_owner_url(module, topic):
    if module not in data.DEV_OWNED:
        return None
    dev_topic = data.TOPIC[topic][1] if topic != 'index' else 'overview'
    if topic != 'index' and dev_topic is None:
        return None
    return '/developer/module-%s-%s.html' % (data.DEV_OWNED[module], dev_topic)


def fix_core_links(page, url_path):
    base = posixpath.dirname(url_path if not url_path.endswith('/') else url_path + 'index.html')

    def repl(m):
        href = m.group(2)
        pm = re.match(r'([^#?]*?)((?:[#?].*)?)$', href)
        target, tail = pm.group(1), pm.group(2)
        if not re.search(r'(^|/)index\.html$', target) or re.match(r'[a-z]+:', target) or target.startswith('/'):
            return m.group(0)
        resolved = posixpath.normpath(posixpath.join(base, target))
        mm = re.match(r'^/the-core/modules/(Magento_\w+)/index\.html$', resolved)
        if mm:  # "back to the module", one level too high in the source
            resolved = '/the-core/modules/%s/html/' % mm.group(1)
        elif resolved == '/the-core/modules/index.html':  # "all modules" lives on the section home
            resolved = '/the-core/'
        else:
            resolved = resolved[: -len('index.html')]
        return m.group(1) + resolved + tail + m.group(3)

    return re.sub(r'(href=")([^"]*)(")', repl, page)


DATE_AFTER = re.compile(
    r'((?:last\s+updated)\s*:?(?:\s*</?(?:strong|dt|dd|b|span)[^>]*>)*\s*)(<time[^>]*>[^<]*</time>|\d{4}-\d{2}-\d{2}|[A-Z][a-z]+ \d{4})',
    re.I)


def replace_typed_dates(page, iso):
    return DATE_AFTER.sub(lambda m: m.group(1) + sh.time_tag(iso), page)


def apply_core(path, refresh):
    url_path, module, topic = core_key(path)
    rel = os.path.relpath(path, ROOT).replace(os.sep, '/')
    original = read(path)
    page = sh.strip_block(original)
    if module is None:
        title, desc, h1 = data.CORE_ROOT_TITLE, data.CORE_ROOT_DESC, None
    else:
        label = data.TOPIC_OVERRIDE.get((module, topic)) or data.TOPIC[topic][0]
        h1 = '%s %s' % (module, 'Module' if topic == 'index' else label)
        title = '%s (Core Docs)' % h1
        desc = data.CORE_DESC[(module, topic)]
    if len(title) > sh.TITLE_MAX:
        raise ValueError('title too long: %r' % title)
    sh.check_description(desc, rel)

    owner = dev_owner_url(module, topic) if module else None
    canonical_override = sh.abs_url(owner) if owner else None

    page = set_title_and_description(page, title, desc)
    if h1:
        page = re.sub(r'(<h1\b[^>]*>)(.*?)(</h1>)', lambda m: m.group(1) + sh.esc(h1).replace('&#x27;', "'") + m.group(3), page, count=1, flags=re.S)

    crumbs = [('Developer Docs', sh.abs_url('/developer/')), ('The Magento Core', sh.abs_url('/the-core/'))]
    if module:
        crumbs.append((module, sh.abs_url('/the-core/modules/%s/html/' % module)))
        if topic != 'index':
            crumbs.append((h1, sh.abs_url(url_path)))
    date = page_date(original, rel, refresh)
    headline = title.replace(' (Core Docs)', '')
    page = insert_block(page, sh.seo_block(title, desc, url_path, headline, crumbs, date, canonical_override))
    page = fix_core_links(page, url_path)
    if date:
        page = replace_typed_dates(page, date)
    if owner:
        page = add_dev_link(page, owner, module, topic, h1)
    return path, page


def add_dev_link(page, owner, module, topic, h1):
    anchor = re.search(r'(<a href="/developer/" aria-label="Back to Developer Docs" class="([^"]*)">.*?</a>)(</div>)', page, re.S)
    if not anchor or 'developer-guide-link' in page:
        return page
    label = 'Developer guide: %s' % (h1 if topic != 'index' else module + ' overview')
    link = ('<a href="%s" class="developer-guide-link %s ml-6">%s <span aria-hidden="true">→</span></a>'
            % (owner, anchor.group(2), sh.esc(label).replace('&amp;', '&amp;')))
    return page.replace(anchor.group(0), anchor.group(1) + link + anchor.group(3), 1)


# ------------------------------------------------------------------ main

def main():
    refresh = '--refresh' in sys.argv
    check = '--check' in sys.argv
    jobs = []
    for name in list(data.DEV_PAGES) + list(data.DEV_LEGACY):
        jobs.append(apply_dev(name, refresh))
    for path in core_pages():
        jobs.append(apply_core(path, refresh))
    changed = 0
    for path, page in jobs:
        if read(path) != page:
            changed += 1
            if not check:
                with open(path, 'w', encoding='utf-8') as f:
                    f.write(page)
    print('%d pages processed, %d %s' % (len(jobs), changed, 'would change' if check else 'updated'))
    return 1 if (check and changed) else 0


if __name__ == '__main__':
    sys.exit(main())
